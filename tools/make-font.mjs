// The HUD font: a signed distance field atlas of ASCII 32..126 and its advance widths.
//   powershell -File tools/font-raster.ps1 <Poppins-Bold.ttf> <tmp>/poppins     (GDI+ coverage, 256 px cells)
//   node tools/make-font.mjs <tmp>/poppins
// Writes textures/font.png (16 x 6 cells of 64 px; the distance in every channel, 0.5 = the outline, SPREAD output
// pixels either side) and Code/FontData.gs (advances in em). Poppins is under the SIL Open Font License
// (textures/FONT-LICENSE.txt).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
const meta = JSON.parse(fs.readFileSync(src + '.json', 'utf8').replace(/^﻿/, ''));
const hi = fs.readFileSync(src + '.bin');
const CELL = meta.cell, COLS = meta.cols, ROWS = meta.rows, W = COLS * CELL, H = ROWS * CELL;
const DOWN = 4, OC = CELL / DOWN, OW = W / DOWN, OH = H / DOWN;
const SPREAD = 6;   // output pixels

// exact Euclidean distance transform (Felzenszwalb & Huttenlocher), squared distances to the nearest "on" pixel
const INF = 1e20;
function edt1(f, n, d, v, z) {
  let k = 0; v[0] = 0; z[0] = -INF; z[1] = INF;
  for (let q = 1; q < n; q++) {
    let s = ((f[q] + q * q) - (f[v[k]] + v[k] * v[k])) / (2 * q - 2 * v[k]);
    while (s <= z[k]) { k--; s = ((f[q] + q * q) - (f[v[k]] + v[k] * v[k])) / (2 * q - 2 * v[k]); }
    k++; v[k] = q; z[k] = s; z[k + 1] = INF;
  }
  k = 0;
  for (let q = 0; q < n; q++) { while (z[k + 1] < q) k++; d[q] = (q - v[k]) * (q - v[k]) + f[v[k]]; }
}
function edt(on, w, h) {
  const g = new Float64Array(w * h);
  for (let i = 0; i < w * h; i++) g[i] = on[i] ? 0 : INF;
  const n = Math.max(w, h), f = new Float64Array(n), d = new Float64Array(n), v = new Int32Array(n), z = new Float64Array(n + 1);
  for (let x = 0; x < w; x++) { for (let y = 0; y < h; y++) f[y] = g[y * w + x]; edt1(f, h, d, v, z); for (let y = 0; y < h; y++) g[y * w + x] = d[y]; }
  for (let y = 0; y < h; y++) { for (let x = 0; x < w; x++) f[x] = g[y * w + x]; edt1(f, w, d, v, z); for (let x = 0; x < w; x++) g[y * w + x] = d[x]; }
  return g;
}
const inside = new Uint8Array(W * H), outside = new Uint8Array(W * H);
for (let i = 0; i < W * H; i++) { inside[i] = hi[i] >= 128 ? 1 : 0; outside[i] = 1 - inside[i]; }
const dOut = edt(inside, W, H), dIn = edt(outside, W, H);
const img = Buffer.alloc(OW * OH * 4);
for (let oy = 0; oy < OH; oy++) for (let ox = 0; ox < OW; ox++) {
  // the centre of the output pixel in hi-res pixels: average the 4 middle samples
  let s = 0;
  for (const [dx, dy] of [[1, 1], [2, 1], [1, 2], [2, 2]]) {
    const i = (oy * DOWN + dy) * W + ox * DOWN + dx;
    s += Math.sqrt(dOut[i]) - Math.sqrt(dIn[i]);
  }
  const dist = s / 4 / DOWN;   // output pixels, + outside
  const val = Math.max(0, Math.min(255, Math.round((0.5 - dist / (2 * SPREAD)) * 255)));
  const o = (oy * OW + ox) * 4;
  img[o] = img[o + 1] = img[o + 2] = val; img[o + 3] = 255;
}
const CRC = (() => { const t = new Int32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c; } return t; })();
const crc32 = (buf) => { let c = -1; for (const b of buf) c = CRC[(c ^ b) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; };
const chunk = (name, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const nd = Buffer.concat([Buffer.from(name, 'latin1'), data]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(nd)); return Buffer.concat([len, nd, crc]); };
const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(OW, 0); ihdr.writeUInt32BE(OH, 4); ihdr[8] = 8; ihdr[9] = 6;
const raw = Buffer.alloc((OW * 4 + 1) * OH);
for (let y = 0; y < OH; y++) img.copy(raw, y * (OW * 4 + 1) + 1, y * OW * 4, (y + 1) * OW * 4);
fs.mkdirSync(path.join(root, 'textures'), { recursive: true });
fs.writeFileSync(path.join(root, 'textures', 'font.png'), Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]));

const adv = meta.glyphs.map((g) => +(g.adv / meta.em).toFixed(4));
const gs = `// Generated by tools/make-font.mjs: the HUD font's metrics (textures/font.png, Poppins Bold, SIL OFL).
// Cells are ${OC} px; one em is ${(meta.em / DOWN).toFixed(2)} px of a cell; the baseline is ${(meta.baseline / CELL).toFixed(3)} of the cell from its top.
public static class FontData
{
	public const float CellEm = ${(CELL / meta.em).toFixed(5)}f;      // a cell's size in em
	public const float Baseline = ${(meta.baseline / CELL).toFixed(5)}f;  // from the top of a cell, in cells
	public const float Spread = ${(2 * SPREAD / OC).toFixed(5)}f;       // the distance field's 0..1 range, in cells
	/// <summary>Advance widths in em of ASCII 32..126.</summary>
	public static readonly float[] Advance = { ${adv.map((a) => a + 'f').join(', ')} };
}
`;
fs.writeFileSync(path.join(root, 'Code', 'FontData.gs'), gs);
console.log(`font: ${OW}x${OH}, ${adv.length} glyphs`);
