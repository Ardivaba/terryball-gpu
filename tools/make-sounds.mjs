// The game's sound list: writes project.json's sgpu.events.sounds and Code/Sounds.gs (each sound's index).
// The announcer's 25 calls come first, two takes each, in Lane.Call order (the Label ids of the calls).
//   node tools/make-sounds.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CALLS = ['strike', 'spare', 'gutter', 'miss', 'open-frame', 'split', 'pocket', 'double', 'turkey', 'four-bagger', 'five-bagger',
  'six-pack', 'perfect-game', 'nice', 'so-close', 'good-try', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
const sounds = [];
for (const c of CALLS) for (const take of [0, 1]) sounds.push(`sounds/announcer/${c}_${take}.wav`);
const THROW = sounds.length; sounds.push('sounds/ball/throw0.wav');
const CLACK = sounds.length; for (let i = 0; i < 6; i++) sounds.push(`sounds/pins/clack${i}.wav`);
const THUD = sounds.length; for (let i = 0; i < 2; i++) sounds.push(`sounds/pins/thud${i}.wav`);
for (const s of sounds) if (!fs.existsSync(path.join(root, s))) throw new Error(`missing ${s}`);

const pj = path.join(root, 'project.json');
const project = JSON.parse(fs.readFileSync(pj, 'utf8'));
project.sgpu.events = { ...(project.sgpu.events || {}), sounds };
fs.writeFileSync(pj, JSON.stringify(project, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'Code', 'Sounds.gs'), `// Generated by tools/make-sounds.mjs: indices into project.json's sgpu.events.sounds.
public static class Sounds
{
	public const int Announcer = 0;        // call c, take k: Announcer + c * 2 + k (c = the call's Label id)
	public const int Throw = ${THROW};
	public const int Clack = ${CLACK};          // 6 variants
	public const int Thud = ${THUD};           // 2 variants
}
`);
console.log(`sounds: ${sounds.length}`);
