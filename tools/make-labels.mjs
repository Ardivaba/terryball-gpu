// GPU# has no strings, so the HUD's fixed text is a table of packed characters: Code/Labels.gs.
// Each label is 8 ints of 4 ASCII characters (the first in the low byte), at most 32 characters; Label.X is its row.
//   node tools/make-labels.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// the announcer's calls first, in the order of Lane.Call ids (the source's ClassifyCall ids)
export const CALLS = [
  ['Strike', 'STRIKE!'], ['Spare', 'SPARE'], ['Gutter', 'GUTTER'], ['Miss', 'MISS'], ['OpenFrame', 'OPEN'], ['Split', 'SPLIT!'],
  ['Pocket', 'POCKET'], ['Double', 'DOUBLE!'], ['Turkey', 'TURKEY!'], ['FourBagger', 'FOUR-BAGGER!'], ['FiveBagger', 'FIVE-BAGGER!'],
  ['SixPack', 'SIX-PACK!'], ['PerfectGame', 'PERFECT GAME!'], ['Nice', 'NICE!'], ['SoClose', 'SO CLOSE!'], ['GoodTry', 'GOOD TRY'],
  ['One', '1'], ['Two', '2'], ['Three', '3'], ['Four', '4'], ['Five', '5'], ['Six', '6'], ['Seven', '7'], ['Eight', '8'], ['Nine', '9'],
];
const LABELS = [
  ...CALLS,
  ['Scoreboard', 'SCOREBOARD'], ['Total', 'TOTAL'], ['Pins', 'PINS'], ['Watching', 'WATCHING'], ['Speed', 'SPEED'], ['Mph', 'mph'],
  ['Line', 'LINE'], ['Aim', 'AIM'], ['Power', 'POWER'], ['Spin', 'SPIN'], ['ClickToSet', 'Click / Space to set'],
  ['StepBack', 'Right-click / Backspace: back'], ['NiceThrow', 'Nice throw!'], ['GameOver', 'GAME OVER'], ['PressP', 'press P for a new game'],
  ['PressPReset', 'press P to reset'], ['Dash', '-'], ['X', 'X'], ['Slash', '/'], ['Player', 'P'], ['Frame', 'FRAME'],
  ['ThrowAim', 'AIM throw'], ['ThrowFree', 'FREE throw'], ['KeyT', 'T'], ['KeyP', 'P'], ['KeyWasd', 'WASD'], ['KeyMouse', 'Mouse'],
  ['HintDrive', 'drive the ball'], ['HintLook', 'look'], ['HintThrowMode', 'aim / free throw'], ['HintReset', 'new game'],
  ['SweetPower', 'tick = sweet spot'], ['SweetSpin', 'ticks = sweet spin'], ['Practice', 'PRACTICE MODE'], ['Lane', 'LANE'],
  ['Terryball', 'TERRYBALL'], ['OpenLane', 'LANE'], ['QuickGame', 'quick game'], ['Join', 'JOIN'], ['Leave', 'LEAVE'],
  ['ThrowMode', 'THROW'], ['Crane', 'BALL CRANE'], ['Start', 'START'], ['Stop', 'STOP'], ['Reset', 'RESET'], ['Free', 'FREE'], ['On', 'ON'],
  ['Off', 'OFF'], ['InPlay', 'IN PLAY'], ['Lobby', 'LOBBY'], ['Joined', 'JOINED'], ['MenuHint', 'W/S pick, Space choose, E close'], ['BallSign', 'BALL'], ['Help', 'HELP'], ['FeedTitle', 'LANE FEED'],
];
const words = [];
for (const [, text] of LABELS) {
  if (text.length > 32) throw new Error(`label too long: ${text}`);
  for (let w = 0; w < 8; w++) {
    let v = 0;
    for (let k = 0; k < 4; k++) { const c = text.charCodeAt(w * 4 + k) || 0; v |= c << (8 * k); }
    words.push(v | 0);
  }
}
const gs = `// Generated by tools/make-labels.mjs: the HUD's fixed text, 8 ints of 4 characters per label (low byte first).
public static class Label
{
${LABELS.map(([name, text], i) => `\tpublic const int ${name} = ${i};   // ${text}`).join('\n')}
	public const int Count = ${LABELS.length};
	public const int Calls = ${CALLS.length};
	public static readonly int[] Words = {
		${words.map((w, i) => (i % 8 === 0 && i ? '\n\t\t' : '') + w).join(', ')}
	};
}
`;
fs.writeFileSync(path.join(root, 'Code', 'Labels.gs'), gs);
console.log(`labels: ${LABELS.length}`);
